"""SQLAlchemy ORM model for Agent Run."""

import uuid
from typing import TYPE_CHECKING, Any

from sqlalchemy import Float, ForeignKey, Index, Integer, String, UniqueConstraint
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from modernization_platform.db.base import Base, ImmutableTimestampMixin
from modernization_platform.db.types import GUID

if TYPE_CHECKING:
    from modernization_platform.db.models.artifact import Artifact
    from modernization_platform.db.models.job import Job
    from modernization_platform.db.models.module_attempt import ModuleAttempt


class AgentRun(Base, ImmutableTimestampMixin):
    """Immutable audit, telemetry, and cost record for every agent step invocation."""

    __tablename__ = "agent_run"

    id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        primary_key=True,
        default=uuid.uuid4,
        comment="Unique agent invocation run identifier",
    )
    job_id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        ForeignKey("job.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
        comment="Parent modernization job",
    )
    module_attempt_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID,
        ForeignKey("module_attempt.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment="Optional module attempt context for CodeWriter/repair steps",
    )
    agent: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        index=True,
        comment="Agent identifier (Intake, Analyzer, Architect, CodeWriter, Verifier...)",
    )
    step_key: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
        comment="Deterministic step key for idempotency enforcement",
    )
    model: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        comment="Configured model name utilized for this invocation",
    )
    prompt_version: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        comment="Versioned prompt template identifier",
    )
    input_artifact_ids: Mapped[list[str]] = mapped_column(
        JSONB,
        nullable=False,
        default=list,
        comment="List of input artifact UUID strings provided to agent context",
    )
    output_artifact_ids: Mapped[list[str]] = mapped_column(
        JSONB,
        nullable=False,
        default=list,
        comment="List of output artifact UUID strings generated by agent",
    )
    tokens_input: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        comment="Metered input prompt token count",
    )
    tokens_output: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        comment="Metered completion token count",
    )
    cost_cents: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.0,
        comment="Calculated financial cost of invocation in cents",
    )
    duration_ms: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        comment="Wall clock duration of the invocation in milliseconds",
    )
    tool_calls: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB,
        nullable=False,
        default=list,
        comment="Structured audit trace of tool executions initiated by agent",
    )

    # Relationships
    job: Mapped["Job"] = relationship("Job", back_populates="agent_runs")
    module_attempt: Mapped["ModuleAttempt | None"] = relationship(
        "ModuleAttempt",
        back_populates="agent_runs",
    )
    produced_artifacts: Mapped[list["Artifact"]] = relationship(
        "Artifact",
        foreign_keys="Artifact.produced_by_run_id",
        back_populates="producer_run",
    )

    __table_args__ = (
        UniqueConstraint(
            "job_id",
            "agent",
            "step_key",
            name="uq_agent_run_idempotency",
        ),
        Index("ix_agent_run_job_agent", "job_id", "agent"),
    )
